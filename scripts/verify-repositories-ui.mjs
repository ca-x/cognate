function rpc(service, method, body = {}, token) {
  return new Promise((done, reject) => {
    const request = https.request(`${ready.url}/skillhub.${service}/${method}`, { method: "POST", rejectUnauthorized: false, timeout: 10000, headers: { "Content-Type": "application/json", "Connect-Protocol-Version": "1", ...(token ? { Authorization: `Bearer ${token}` } : {}) } }, (response) => {
      let data = ""
      response.on("data", (chunk) => { data += chunk })
      response.on("end", () => { try { done({ status: response.statusCode, body: JSON.parse(data) }) } catch { reject(new Error("invalid RPC receipt")) } })
    })
    request.on("error", reject)
    request.on("timeout", () => request.destroy(new Error("fixture RPC timeout")))
    request.end(JSON.stringify(body))
  })
}
