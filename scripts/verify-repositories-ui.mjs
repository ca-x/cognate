function layout(name) {
  const result = evaluate(`(() => {
    const root = document.querySelector('[role=dialog]') ?? document.querySelector('.repositories-ui, .categories-ui')
    const elements = [...root.querySelectorAll('*')].filter(node => {
      const rect = node.getBoundingClientRect(), style = getComputedStyle(node)
      return rect.width && rect.height && style.visibility !== 'hidden' && (rect.left < -1 || rect.right > innerWidth + 1 || node.scrollWidth > node.clientWidth + 1 && style.overflowX === 'hidden')
    }).map(node => ({tag: node.tagName, className: node.className, text: node.textContent.slice(0,80), clientWidth: node.clientWidth, scrollWidth: node.scrollWidth, left: node.getBoundingClientRect().left, right: node.getBoundingClientRect().right}))
    const words = [], textOutside = []
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT)
    while (walker.nextNode()) {
      const node = walker.currentNode
      const textRange = document.createRange(); textRange.selectNodeContents(node)
      if ([...textRange.getClientRects()].some(rect => rect.left < -1 || rect.right > innerWidth + 1)) textOutside.push(node.textContent.slice(0,80))
      if (getComputedStyle(node.parentElement).fontFamily.includes('mono')) continue
      for (const match of node.textContent.matchAll(/[A-Za-z]{3,}/g)) {
        const range = document.createRange(); range.setStart(node, match.index); range.setEnd(node, match.index + match[0].length)
        if (range.getClientRects().length > 1) words.push(match[0])
      }
    }
    return { width: innerWidth, scrollWidth: document.documentElement.scrollWidth, fontSize: getComputedStyle(document.documentElement).fontSize, elements, words, textOutside }
  })()`)
  layouts.push({ name, ...result })
  assert(result.scrollWidth <= result.width + 1, `${name}: page overflow`)
  assert.deepEqual(result.elements, [], `${name}: clipped or overflowing elements`)
  assert.deepEqual(result.words, [], `${name}: split English words`)
  assert.deepEqual(result.textOutside, [], `${name}: text outside the viewport`)
}
