func geminiNativeIdentity() GeminiProfileIdentity {
	id, source, codec := geminiconfig.Native0610CodecIdentity()
	manifest, _ := hex.DecodeString(geminiconfig.Native0610PackageManifestSHA256)
	node, _ := hex.DecodeString(geminiconfig.Native0610NodeSHA256)
	contract, _ := json.Marshal(struct {
		ID                            string
		Source, Manifest, Codec, Node [32]byte
		Observer                      string
	}{id, source, [32]byte(manifest), codec, [32]byte(node), "noexec/trusted-existing-root/two-role-cas/v1"})
	return GeminiProfileIdentity{ID: id, ManifestSHA256: [32]byte(manifest), ProfileSHA256: sha256.Sum256(contract), CodecSHA256: codec, NodeSHA256: [32]byte(node)}
}
func QualifiedGeminiNativeProfile() (GeminiProfileIdentity, error) {
	profile := geminiNativeIdentity()
	if runtime.GOOS != "linux" || runtime.GOARCH != "amd64" || geminiPlatform() != nil {
		return GeminiProfileIdentity{}, ErrGeminiUnsupported
	}
	for _, qualified := range geminiQualifiedProfiles {
		if qualified == profile {
			return profile, nil
		}
	}
	return GeminiProfileIdentity{}, ErrGeminiUnsupported
}
